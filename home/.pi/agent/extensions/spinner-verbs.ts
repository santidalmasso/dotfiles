export const SPINNER_VERBS = [
  ...SHORT_SPINNER_VERBS,
  ...LONG_SPINNER_VERBS,
] as const;


function pickRandomSpinnerVerb(): string {
  return SPINNER_VERBS[Math.floor(Math.random() * SPINNER_VERBS.length)];
}

export default function spinnerVerbsExtension(pi: ExtensionAPI) {
  pi.on("turn_start", async (_event, ctx) => {
    if (!ctx.hasUI) return;
    ctx.ui.setWorkingMessage(pickRandomSpinnerVerb());
  });

  pi.on("turn_end", async (_event, ctx) => {
    if (!ctx.hasUI) return;
    ctx.ui.setWorkingMessage();
  });

  pi.on("agent_end", async (_event, ctx) => {
    if (!ctx.hasUI) return;
    ctx.ui.setWorkingMessage();
  });
}
